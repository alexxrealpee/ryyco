const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const React = require('react');
const { JSDOM } = require('jsdom');
const { createRoot } = require('react-dom/client');
async function main() {
 const dom = new JSDOM('<div id="root"></div>');
 Object.assign(globalThis, {window:dom.window, document:dom.window.document, IS_REACT_ACT_ENVIRONMENT:true});
 const calls=[];
 const map={setZoom:z=>calls.push(['zoom',z]),setCenter:p=>calls.push(['center',p]),panBy:(x,y)=>calls.push(['pan',x,y]),fitBounds:(b,p)=>calls.push(['fit',b.points,p])};
 globalThis.google={maps:{LatLngBounds:class {points=[];extend(p){this.points.push(p)}}}};
 const code=ts.transpileModule(fs.readFileSync('src/components/TrackingMapCamera.tsx','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
 const mod={exports:{}};
 new Function('require','exports',code)(name=>name==='react'?React:{useMap:()=>map},mod.exports);
 const Component=mod.exports.GoogleMapCameraController;
 const root=createRoot(document.getElementById('root'));
 const padding={top:84,bottom:310,left:28,right:28};
 let props={points:[{lat:1,lng:2}],driver:null,padding,centerModeTrigger:{mode:'all',id:1}};
 const render=()=>React.act(async()=>root.render(React.createElement(Component,props)));
 await render();
 assert.deepEqual(calls,[['zoom',16],['center',props.points[0]],['pan',0,113]]);
 calls.length=0;
 props={...props,driver:{lat:2,lng:3},points:[{lat:1,lng:2},{lat:2,lng:3}]};
 await render();assert.equal(calls[0][0],'fit');
 calls.length=0;
 props={...props,driver:{lat:3,lng:4},points:[{lat:1,lng:2},{lat:3,lng:4}]};
 await render();assert.equal(calls.length,0,'Live GPS must not reset manual zoom');
 props={...props,centerModeTrigger:{mode:'driver',id:2}};
 await render();
 assert.deepEqual(calls,[['zoom',16],['center',{lat:3,lng:4}],['pan',0,113]]);
 calls.length=0;
 props={...props,padding:{...padding,bottom:210}};
 await render();assert.deepEqual(calls.at(-1),['pan',0,63]);
 await React.act(async()=>root.unmount());
 dom.window.close();
 console.log('PASS camera: initial bounds, first GPS, manual zoom preserved, latest driver centered above panel, resized padding.');
}
main().catch(e=>{console.error(e);process.exitCode=1});
